const ARABIC_DIGITS = '٠١٢٣٤٥٦٧٨٩';

export function toArabicDigits(value: number | string): string {
  return String(value).replace(/\d/g, (d) => ARABIC_DIGITS[Number(d)]);
}

/** "2:20" → "البقرة ٢٠" */
export function formatAyahRef(ref: string): string {
  const [surah, ayah] = ref.split(':').map(Number);
  const name = SURAH_NAMES[surah - 1];
  if (!name || !ayah) return ref;
  return `${name} ${toArabicDigits(ayah)}`;
}

/** "2:1", "2:5" → "البقرة ١–٥"; across surahs → "البقرة ٢٨٠ – آل عمران ٣" */
export function formatAyahRange(start: string, end: string): string {
  const [s1, a1] = start.split(':').map(Number);
  const [s2, a2] = end.split(':').map(Number);
  if (s1 === s2) return a1 === a2 ? formatAyahRef(start) : `${SURAH_NAMES[s1 - 1] ?? s1} ${toArabicDigits(a1)}–${toArabicDigits(a2)}`;
  return `${formatAyahRef(start)} – ${formatAyahRef(end)}`;
}
